// The route table generator (api.md 4, 55) and the API reference (api.md 1, 55): auth comes from the security requirements, path
// parameters must be declared, and x-agent must be a boolean.
import { test } from 'node:test';
import assert from 'node:assert/strict';
import { readFileSync } from 'node:fs';
import { COMMANDS_OUT, OUT, REFERENCE_OUT, SPEC, TOOLS_OUT, authOf, commandsOf, inputType, loadSchemas, operationsOf, render, renderCommands, shape } from './gen-api.mjs';
import { renderReference } from './gen-reference.mjs';
import { undescribedInputs, undescribedOutputs } from './schema-descriptions.mjs';

const doc = (operation, route = '/api/boards/{board}', parameters = { board: { name: 'board', in: 'path' } }) => ({
  paths: { [route]: { get: { operationId: 'get_board', 'x-agent': true, parameters: [{ $ref: '#/components/parameters/board' }], ...operation } } },
  components: { parameters },
});

test('auth: an empty requirement means anyone; otherwise the one scheme named', () => {
  assert.equal(authOf('x', undefined), 'none');
  assert.equal(authOf('x', []), 'none');
  assert.equal(authOf('x', [{}, { agentSecret: [] }]), 'none');
  assert.equal(authOf('x', [{ agentSecret: [] }]), 'agent');
  assert.equal(authOf('x', [{ personCookie: [] }]), 'person');
  assert.equal(authOf('x', [{ runToken: [] }]), 'run');
  assert.throws(() => authOf('x', [{ agentSecret: [] }, { personCookie: [] }]), /one scheme/);
  assert.throws(() => authOf('x', [{ oauth: [] }]), /unknown security scheme/);
});

test('each operation becomes a row with its path parameters, in order', () => {
  const rows = operationsOf(doc({ security: [{ agentSecret: [] }] }));
  assert.deepEqual(rows, [{ operationId: 'get_board', method: 'GET', path: '/api/boards/{board}', pathParams: ['board'], xAgent: true, auth: 'agent' }]);
});

test('a path parameter that is not declared, a missing operationId and a non-boolean x-agent are refused', () => {
  assert.throws(() => operationsOf(doc({}, '/api/boards/{board}/nodes/{n}')), /path parameters/);
  assert.throws(() => operationsOf(doc({ operationId: undefined })), /no operationId/);
  assert.throws(() => operationsOf(doc({ 'x-agent': 'yes' })), /x-agent/);
});

test('the rendered file names every operation and says it is generated', () => {
  const text = render(doc({}));
  assert.match(text, /^\/\/ GENERATED by scripts\/gen-api\.mjs/);
  assert.match(text, /get_board: \{/);
  assert.match(text, /satisfies Record<string, OperationInfo>/);
});

// --- the `vb` command table (api.md 51, 55) ---
const schemas = new Map([
  ['https://x.invalid/common.json', { $id: 'https://x.invalid/common.json', $defs: {
    text: { type: 'string', pattern: '\\S' },
    label: { $ref: 'https://x.invalid/common.json#/$defs/text', maxLength: 80, description: 'A label.' },
    count: { type: 'integer', minimum: 1 },
  } }],
  ['https://x.invalid/body.json', { $id: 'https://x.invalid/body.json', type: 'object', required: ['label'],
    properties: { label: { $ref: 'https://x.invalid/common.json#/$defs/label' }, tags: { type: 'array', items: { type: 'string' } } },
    allOf: [{ required: ['count'], properties: { count: { $ref: 'https://x.invalid/common.json#/$defs/count' }, on: { type: 'boolean' } } }] }],
]);
const agentDoc = {
  paths: {
    '/api/things/{thing}': {
      get: { operationId: 'show_thing', summary: 'Show a thing', description: 'Shows it.', 'x-agent': true,
        parameters: [{ name: 'thing', in: 'path', required: true, description: 'Which.', schema: { $ref: 'https://x.invalid/common.json#/$defs/text' } },
          { name: 'wait', in: 'query', schema: { $ref: 'https://x.invalid/common.json#/$defs/count' }, description: 'Seconds.' }] },
      post: { operationId: 'make_thing', summary: 'Make', 'x-agent': true,
        parameters: [{ name: 'thing', in: 'path', required: true, schema: { type: 'string' } }],
        requestBody: { content: { 'application/json': { schema: { $ref: 'https://x.invalid/body.json' } } } } },
    },
    '/api/person': { post: { operationId: 'act', summary: 'Person only', 'x-agent': false } },
  },
};

test('a schema folds its $ref and allOf: own keywords win, properties and required add up', () => {
  const s = shape({ $ref: 'https://x.invalid/common.json#/$defs/label' }, {}, schemas);
  assert.deepEqual([s.type, s.maxLength, s.description], ['string', 80, 'A label.']);
  const body = shape({ $ref: 'https://x.invalid/body.json' }, {}, schemas);
  assert.deepEqual(Object.keys(body.properties), ['count', 'on', 'label', 'tags']);
  assert.deepEqual(body.required.sort(), ['count', 'label']);
});

test('input types: string, integer, boolean; anything else (an array) is json', () => {
  const t = (schema) => inputType(schema, {}, schemas);
  assert.equal(t({ $ref: 'https://x.invalid/common.json#/$defs/label' }), 'string');
  assert.equal(t({ $ref: 'https://x.invalid/common.json#/$defs/count' }), 'integer');
  assert.equal(t({ type: 'boolean' }), 'boolean');
  assert.equal(t({ enum: ['a', 'b'] }), 'string');
  assert.equal(t({ type: 'array' }), 'json');
  assert.equal(t({ oneOf: [{ type: 'string' }, { type: 'integer' }] }), 'json');
});

test('commands: only x-agent operations; hyphenated name; path, query, then body inputs with required and description', () => {
  const commands = commandsOf(agentDoc, schemas);
  assert.deepEqual(commands.map((c) => [c.name, c.operationId, c.takesBody]), [['show-thing', 'show_thing', false], ['make-thing', 'make_thing', true]]);
  assert.deepEqual(commands[0].inputs, [
    { name: 'thing', in: 'path', type: 'string', required: true, description: 'Which.' },
    { name: 'wait', in: 'query', type: 'integer', required: false, description: 'Seconds.' },
  ]);
  assert.deepEqual(commands[1].inputs.map((i) => [i.name, i.in, i.type, i.required]),
    [['thing', 'path', 'string', true], ['count', 'body', 'integer', true], ['on', 'body', 'boolean', false], ['label', 'body', 'string', true], ['tags', 'body', 'json', false]]);
  assert.equal(commands[1].inputs.find((i) => i.name === 'label').description, 'A label.');
});

test('an input named twice in one command is refused', () => {
  const doc = structuredClone(agentDoc);
  doc.paths['/api/things/{thing}'].post.parameters[0].name = 'label';
  doc.paths['/api/things/{thing}'].post.requestBody.content['application/json'].schema = { type: 'object', properties: { label: { type: 'string' } } };
  doc.paths['/api/things/{label}'] = doc.paths['/api/things/{thing}'];
  delete doc.paths['/api/things/{thing}'];
  assert.throws(() => commandsOf(doc, schemas), /named twice/);
});

test('the rendered command table says it is generated and holds every command', () => {
  const text = renderCommands(agentDoc, schemas);
  assert.match(text, /^\/\/ GENERATED by scripts\/gen-api\.mjs/);
  assert.match(text, /name: "show-thing", operationId: "show_thing", takesBody: false,/);
  assert.match(text, /export const COMMANDS: readonly CommandInfo\[\] = \[/);
});

test('packages/cli/src/commands.generated.ts is current with openapi.json', () => {
  const text = renderCommands(JSON.parse(readFileSync(SPEC, 'utf8')), loadSchemas());
  assert.equal(readFileSync(COMMANDS_OUT, 'utf8'), text, 'run: npm run gen');
});

// --- the API reference and the descriptions (api.md 1, 55) ---
const realDoc = () => JSON.parse(readFileSync(SPEC, 'utf8'));

test('docs/specification/api-reference.md is current with openapi.json', () => {
  const doc = realDoc();
  assert.equal(readFileSync(REFERENCE_OUT, 'utf8'), renderReference(doc, loadSchemas(), operationsOf(doc)), 'run: npm run gen');
});

test('the reference says it is generated and names every operation, its path, its tool and its command', () => {
  const doc = realDoc();
  const text = readFileSync(REFERENCE_OUT, 'utf8');
  assert.match(text, /^# Board API reference\n\n> Generated by `npm run gen`/);
  for (const o of operationsOf(doc)) {
    assert.ok(text.includes(`## \`${o.operationId}\``), `${o.operationId} has a section`);
    assert.ok(text.includes(`\`${o.method} ${o.path}\``), `${o.operationId} shows its method and path`);
    if (o.xAgent) assert.ok(text.includes(`\`vb ${o.operationId.replaceAll('_', '-')}\``), `${o.operationId} shows its vb command`);
  }
  for (const heading of ['### Inputs', '### Answer', '### Errors']) assert.ok(text.includes(heading), heading);
});

test('every input of every operation, and every field of every answer, has a description', () => {
  const doc = realDoc();
  assert.deepEqual(undescribedInputs(doc, loadSchemas()), [], 'describe these inputs in their schema');
  assert.deepEqual(undescribedOutputs(doc, loadSchemas()), [], 'describe these answer fields in their schema');
});

test('a property with no description anywhere is found, and a described $ref target counts', () => {
  const ID = 'https://x.invalid/s.json';
  const s = new Map([[ID, { $id: ID, $defs: { named: { type: 'string', description: 'A name.' }, bare: { type: 'string' } } }]]);
  const doc = { paths: { '/x': { post: { operationId: 'x', requestBody: { content: { 'application/json': { schema: { type: 'object', properties: {
    ok: { $ref: `${ID}#/$defs/named` }, own: { $ref: `${ID}#/$defs/bare`, description: 'Own.' }, missing: { $ref: `${ID}#/$defs/bare` },
    list: { type: 'array', description: 'A list.', items: { type: 'object', properties: { deep: { type: 'integer' } } } },
  } } } } } } } } };
  assert.deepEqual(undescribedInputs(doc, s), [`openapi.json#/properties/missing`, `openapi.json#/properties/list/items/properties/deep`]);
});

test('no generated tool, command, route table or reference text cites our own docs', () => {
  for (const file of [TOOLS_OUT, COMMANDS_OUT, OUT, REFERENCE_OUT]) {
    const text = readFileSync(file, 'utf8');
    for (const banned of ['api.md', 'D-0', 'rule ']) assert.ok(!text.includes(banned), `${file} contains "${banned}"`);
  }
});

test('no schema title or description cites our own docs; the pointer lives in $comment', () => {
  const banned = /api\.md|\bD-0\d|\brule \d/;
  const bad = [];
  const walk = (node, where) => {
    if (Array.isArray(node)) return node.forEach((x, i) => walk(x, `${where}/${i}`));
    if (typeof node !== 'object' || node === null) return;
    for (const [k, v] of Object.entries(node)) {
      if ((k === 'title' || k === 'description') && typeof v === 'string' && banned.test(v)) bad.push(`${where}/${k}: ${v}`);
      walk(v, `${where}/${k}`);
    }
  };
  walk(realDoc(), 'openapi.json');
  for (const [id, schema] of loadSchemas()) walk(schema, id);
  assert.deepEqual(bad, []);
});
