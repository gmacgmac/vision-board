// Route table generator (api.md 1, 4, 53, 55): reads packages/format/schema/openapi.json and writes
// packages/format/src/operations.generated.ts, the one table the server, client, MCP tools and vb
// read instead of openapi.json. Run: npm run gen. `--check` exits 1 if the file would change.
import { existsSync, readFileSync, writeFileSync } from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
export const SPEC = path.join(ROOT, 'packages/format/schema/openapi.json');
export const OUT = path.join(ROOT, 'packages/format/src/operations.generated.ts');
const METHODS = ['get', 'put', 'post', 'delete', 'options', 'head', 'patch', 'trace', 'query'];
const SCHEME_AUTH = { agentSecret: 'agent', personCookie: 'person' };

/** Who a call needs to be: `none` when any caller may (an empty requirement is an alternative). */
export function authOf(operationId, security) {
  if (!Array.isArray(security) || security.length === 0 || security.some((r) => Object.keys(r).length === 0)) return 'none';
  const schemes = new Set(security.flatMap((r) => Object.keys(r)));
  if (schemes.size !== 1) throw new Error(`${operationId}: security must name one scheme`);
  const auth = SCHEME_AUTH[[...schemes][0]];
  if (!auth) throw new Error(`${operationId}: unknown security scheme ${[...schemes][0]}`);
  return auth;
}

const resolve = (doc, p) => {
  if (!p.$ref) return p;
  const name = p.$ref.replace('#/components/parameters/', '');
  if (!p.$ref.startsWith('#/components/parameters/') || !doc.components?.parameters?.[name]) throw new Error(`unresolved parameter ${p.$ref}`);
  return doc.components.parameters[name];
};

/** The operations of an OpenAPI document, in document order. */
export function operationsOf(doc) {
  const out = [];
  for (const [route, item] of Object.entries(doc.paths ?? {})) {
    for (const method of METHODS.filter((m) => item[m])) {
      const op = item[method];
      const id = op.operationId;
      if (typeof id !== 'string') throw new Error(`${method.toUpperCase()} ${route}: no operationId`);
      const pathParams = [...route.matchAll(/\{([^}]+)\}/g)].map((m) => m[1]);
      const declared = (op.parameters ?? []).map((p) => resolve(doc, p)).filter((p) => p.in === 'path').map((p) => p.name);
      if (declared.join() !== pathParams.join()) throw new Error(`${id}: path parameters [${declared}] do not match ${route}`);
      if (typeof op['x-agent'] !== 'boolean') throw new Error(`${id}: x-agent must be true or false`);
      out.push({ operationId: id, method: method.toUpperCase(), path: route, pathParams, xAgent: op['x-agent'], auth: authOf(id, op.security) });
    }
  }
  return out;
}

const q = (s) => `'${s}'`;

/** The text of operations.generated.ts for a document. */
export function render(doc) {
  const rows = operationsOf(doc).map((o) => [
    `  ${o.operationId}: {`,
    `    operationId: ${q(o.operationId)}, method: ${q(o.method)}, path: ${q(o.path)},`,
    `    pathParams: [${o.pathParams.map(q).join(', ')}], xAgent: ${o.xAgent}, auth: ${q(o.auth)},`,
    '  },',
  ].join('\n'));
  return [
    '// GENERATED by scripts/gen-api.mjs from packages/format/schema/openapi.json. Do not edit; run `npm run gen`.',
    '// The route table (api.md 1, 4): every operation\'s id, method, path and path parameters, whether agents get it,',
    '// and which credential it needs. Callers read this, never openapi.json, so the page bundle stays small (rule 15).',
    '',
    "export type OperationAuth = 'none' | 'agent' | 'person';",
    '',
    'export interface OperationInfo {',
    '  readonly operationId: string;',
    "  readonly method: 'GET' | 'POST' | 'PUT' | 'PATCH' | 'DELETE';",
    '  /** The path template, such as `/api/boards/{board}`. */',
    '  readonly path: string;',
    '  /** The `{names}` in the path, in order. */',
    '  readonly pathParams: readonly string[];',
    '  /** True when MCP and `vb` get this operation. */',
    '  readonly xAgent: boolean;',
    '  /** `agent`: Bearer secret. `person`: the page cookie. `none`: no credentials needed. */',
    '  readonly auth: OperationAuth;',
    '}',
    '',
    'export const OPERATIONS = {',
    ...rows,
    '} as const satisfies Record<string, OperationInfo>;',
    '',
    'export type OperationId = keyof typeof OPERATIONS;',
    '',
  ].join('\n');
}

function main(argv) {
  const text = render(JSON.parse(readFileSync(SPEC, 'utf8')));
  if (argv.includes('--check')) {
    if (!existsSync(OUT) || readFileSync(OUT, 'utf8') !== text) {
      console.error('gen-api: operations.generated.ts is out of date. Run: npm run gen');
      return 1;
    }
    console.log('gen-api: operations.generated.ts is current');
    return 0;
  }
  writeFileSync(OUT, text);
  console.log(`gen-api: wrote ${path.relative(ROOT, OUT)}`);
  return 0;
}

if (process.argv[1] === fileURLToPath(import.meta.url)) process.exitCode = main(process.argv.slice(2));
